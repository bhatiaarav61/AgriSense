/**
 * Quick benchmark runner for CI/CD
 */
export async function runQuickBenchmark(
  modelPath: string,
  format: string,
  outputDir: string
): Promise<BenchmarkResult> {
  const config: BenchmarkConfig = {
    modelPaths: { [format]: modelPath },
    devices: ['cpu'],
    batchSizes: [1],
    runs: 50,
    warmupRuns: 10,
    outputDir,
    inputShape: [1, 224, 224, 3],
    numClasses: 100,
  };

  const benchmark = new ModelBenchmark(config);
  const results = await benchmark.runAll();
  return results[0];
}